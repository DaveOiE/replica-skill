// design/tokens.*.json -> src/styles/tokens.css (custom properties). Components use var(--c-*), never raw hex.
import { readFileSync, writeFileSync } from 'node:fs';
const read = (f) => JSON.parse(readFileSync(f, 'utf8')).color;
const vars = (c) => Object.entries(c).map(([k, v]) => `  --c-${k}: ${v};`).join('\n');
const light = read('design/tokens.light.json'), dark = read('design/tokens.dark.json');
const missing = Object.keys(light).filter((k) => !(k in dark));
if (missing.length) { console.error('dark theme is missing roles:', missing.join(', ')); process.exit(1); }
writeFileSync('src/styles/tokens.css',
`/* GENERATED by scripts/gen-tokens.mjs from design/tokens.*.json. Do not edit. */
:root, :root[data-theme='light'] {\n${vars(light)}\n  color-scheme: light;\n}
:root[data-theme='dark'] {\n${vars(dark)}\n  color-scheme: dark;\n}
@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']):not([data-theme='dark']) {\n${vars(dark).replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}
`);
console.log('tokens.css written');
