// Bundles the SQL files in /drizzle into a TS module so the browser can apply the same migrations.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const files = readdirSync('drizzle').filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(`drizzle/${f}`, 'utf8'))} },`).join('\n');
writeFileSync('src/schema/migrations.generated.ts', `// GENERATED by scripts/gen-migrations.mjs. Do not edit.\nexport const migrations: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log('migrations:', files.join(', '));
