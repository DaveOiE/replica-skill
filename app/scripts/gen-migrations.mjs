// Bundles the SQL in /drizzle (shared) and /server-migrations (server only) into a TS module, plus a schema
// version hash. The browser applies the same shared migrations as the server, byte for byte.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
const read = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.sql')).sort() : []).map((f) => ({ name: f, sql: readFileSync(`${dir}/${f}`, 'utf8') }));
const shared = read('drizzle'), server = read('server-migrations');
const hash = createHash('sha256').update(shared.map((m) => m.name + m.sql).join('\n')).digest('hex').slice(0, 16);
const lit = (list) => list.map((m) => `  { name: ${JSON.stringify(m.name)}, sql: ${JSON.stringify(m.sql)} },`).join('\n');
writeFileSync('src/schema/migrations.generated.ts',
`// GENERATED by scripts/gen-migrations.mjs. Do not edit.
export const migrations: { name: string; sql: string }[] = [\n${lit(shared)}\n];
export const serverMigrations: { name: string; sql: string }[] = [\n${lit(server)}\n];
/** Changes whenever the shared schema changes. Devices and the server must match to sync. */
export const SCHEMA_VERSION = ${JSON.stringify(hash)};
`);
console.log(`migrations: ${shared.length} shared, ${server.length} server; schema ${hash}`);
