#!/usr/bin/env python3
"""Render STATUS.md from replica/features.csv and replica/milestones.csv.

    python3 tools/status.py            # writes STATUS.md
    python3 tools/status.py --check    # exit 1 if STATUS.md is out of date

Feature state comes from the `clone` column: yes is done (a local mock is
said so), partial is stubbed or setting only, no is not started, skip is
skipped. Milestone state is worked out from its features. Standard library only.
"""
import argparse
import csv
import datetime
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN_SHARE_OF_SESSION = 55  # percent of the session budget set aside for Run (replica/frame.md)
BUILT = ("done", "done (local mock)", "stubbed", "setting only")


def read(path):
    with open(path, newline="", encoding="utf-8-sig") as fh:
        return [{k.strip().lower(): (v or "").strip() for k, v in r.items()}
                for r in csv.DictReader(fh)]


def state(row):
    clone, ceiling = row["clone"].lower(), row.get("ceiling", "").lower()
    if clone in ("yes", "done"):
        return "done (local mock)" if ceiling == "mock" else "done"
    if clone == "partial":
        if ceiling in ("stub", "setting only"):
            return "stubbed" if ceiling == "stub" else "setting only"
        return "partly done"
    if clone == "skip":
        return "skipped"
    return "later (deferred)" if scope(row) == "later" else "not started"


def scope(row):
    return (row.get("scope") or "demo").lower()


def remaining(row):
    """Points still to build in the demo scope: only rows not started (a partial row's rest is inside later screens' points)."""
    return points(row) if scope(row) == "demo" and row["clone"].lower() in ("no", "") else 0


def points(row):
    try:
        return int(row.get("effort") or 0)
    except ValueError:
        return 0


def milestone_state(feats):
    counted = [f for f in feats if f["clone"].lower() != "skip" and scope(f) == "demo"]
    if not counted:
        return "later"
    built = [f for f in counted if state(f) in BUILT]
    partial = [f for f in counted if state(f) == "partly done"]
    if len(built) + len(partial) == len(counted):
        return "done" if not partial else "done, %d partial" % len(partial)
    return "in progress" if (built or partial) else "not started"


def render(features, milestones, today=None, budget=None):
    today = today or datetime.date.today().isoformat()
    budget = budget or {}
    counts = {}
    for f in features:
        counts[state(f)] = counts.get(state(f), 0) + 1
    order = ["done", "done (local mock)", "stubbed", "setting only", "partly done",
             "not started", "later (deferred)", "skipped"]
    out = ["# Status", "", "Generated by `python3 tools/status.py` from "
           "`replica/features.csv`. Do not edit by hand.", "", "Updated: %s" % today, "",
           "## Summary", "", "| state | features |", "| --- | --- |"]
    for s in order:
        if s in counts:
            out.append("| %s | %d |" % (s, counts[s]))
    total_pts = sum(points(f) for f in features)
    built_pts = sum(points(f) for f in features if state(f) in BUILT)
    demo_pts = sum(points(f) for f in features if scope(f) == "demo")
    later_pts = sum(points(f) for f in features if scope(f) == "later")
    pct = (100.0 * built_pts / demo_pts) if demo_pts else 0.0
    out += ["| **total** | **%d** |" % len(features), "",
            "Demo scope: **%d of %d points built (%.0f%%)**. Later pool: %d points, not scheduled. "
            "One point is a small tested feature (a few routes, one screen state, its tests)."
            % (built_pts, demo_pts, pct, later_pts), ""]
    rate = budget.get("rate_percent_per_point")
    used = budget.get("used_percent")
    stop = budget.get("stop_line_percent")
    cols = "| id | milestone | scope | demo pts | to build | later pts | state |"
    sep = "| --- | --- | --- | --- | --- | --- | --- |"
    if rate is not None and used is not None:
        cols += " cost at M1 rate | session % when done |"
        sep += " --- | --- |"
        out += ["## Budget", "",
                "Used so far (proxy): **%.1f%%**. Rate: **%.2f%% of session per point** (measured on M1). "
                "Stop line: **%.0f%%**." % (used, rate, stop or 0), ""]
    out += ["## Milestones", "", cols, sep]
    running = used if used is not None else 0.0
    fits = []
    for m in milestones:
        fs = [f for f in features if f.get("milestone") == m["id"]]
        mscope = (m.get("scope") or "demo").lower()
        dpts = sum(points(f) for f in fs if scope(f) == "demo")
        todo = sum(remaining(f) for f in fs)
        lpts = sum(points(f) for f in fs if scope(f) == "later")
        row = "| %s | %s | %s | %d | %d | %d | %s |" % (m["id"], m["name"], mscope, dpts, todo, lpts, milestone_state(fs))
        if rate is not None and used is not None:
            cost = todo * rate
            running += cost
            row += " %.1f%% | %s |" % (cost, ("%.1f%%" % running) if todo else "-")
            if todo and stop is not None and running <= stop:
                fits.append(m["id"])
        out.append(row)
    if rate is not None and used is not None and stop is not None:
        out += ["", "Fits inside the %.0f%% stop line at the M1 rate: %s." % (stop, ", ".join(fits) if fits else "nothing"),
                "(Gauge and Evolve are extra: see replica/run-plan.md.)"]
    out += ["", "## Features", "", "| milestone | feature | tag | priority | effort | scope | state | note |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for f in sorted(features, key=lambda r: (int(r["milestone"][1:]) if r.get("milestone") else 99, r["area"])):
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            f.get("milestone", ""), f["feature"], f.get("tag", ""), f["priority"],
            points(f), scope(f), state(f), f["notes"].replace("|", "/")))
    out += ["", "Legend: done = works and is tested; done (local mock) = real protocol "
            "against a local stand-in; stubbed = interface exists, nothing real behind it; "
            "setting only = labelled setting and document, not certified; "
            "later (deferred) = in the full list, not in this demo build, still counts against full parity; "
            "skipped = deliberately never built.", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=ROOT)
    args = ap.parse_args(argv)
    features = read(os.path.join(args.root, "replica", "features.csv"))
    milestones = read(os.path.join(args.root, "replica", "milestones.csv"))
    target = os.path.join(args.root, "STATUS.md")
    bpath = os.path.join(args.root, "replica", "budget.json")
    budget = json.load(open(bpath, encoding="utf-8")) if os.path.exists(bpath) else None
    if args.check:
        # compare ignoring the date line so --check works on any day
        old = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        stamp = next((l for l in old.splitlines() if l.startswith("Updated: ")), "Updated: ")
        new = render(features, milestones, today=stamp[len("Updated: "):], budget=budget)
        if old != new:
            print("STATUS.md is out of date: run python3 tools/status.py")
            return 1
        return 0
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(render(features, milestones, budget=budget))
    return 0


if __name__ == "__main__":
    sys.exit(main())
